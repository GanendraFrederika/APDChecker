"""HOST-only pan/tilt sequencing; never drives a servo or sends serial.

Coordinator metadata must be captured with each exposure. Timer completion is
NOT proof that a real servo reached its pose. The MCU/position adapter and its
protocol remain unimplemented/uncommissioned. Do not merge IDs across moves.
"""
from dataclasses import dataclass
import math


@dataclass(frozen=True)
class MotionSettings:
    # Development timings, NOT measured mechanical/calibration values.
    settle_seconds: float = 1.0
    movement_timeout_seconds: float = 3.0

    def __post_init__(self):
        for name in ('settle_seconds', 'movement_timeout_seconds'):
            value = getattr(self, name)
            if (type(value) not in (int, float) or not math.isfinite(value) or
                    not 0 < value <= 60):
                raise ValueError('Invalid ' + name)


@dataclass(frozen=True)
class CameraView:
    camera_view_epoch: int
    camera_view_unstable: bool
    state: str
    reason: str | None
    hardware_outputs_enabled: bool = False

    def tracker_kwargs(self):
        return dict(camera_view_epoch=self.camera_view_epoch,
                    camera_view_unstable=self.camera_view_unstable)


class CameraMotionGate:
    """Fixed view by default; serialized move/ack/settle with fail-closed timeout.

    Owns one tracker. begin_move invalidates its cache/report BEFORE any proposed
    physical command. Caller MUST replace the held report with the returned one.
    Request angles/pulses are intentionally absent until servos, power, stops and
    pin/protocol limits are calibrated. Only one motion can be outstanding.
    """
    def __init__(self, tracker, settings=None):
        self.tracker = tracker
        self.settings = settings or MotionSettings()
        self.state = 'STABLE'
        self.reason = None
        self.last_time = None
        self.deadline = None
        self.stable_at = None

    def _invalidate(self):
        return self.tracker.invalidate_camera_view(self.tracker.camera_view_epoch + 1)

    def _fail(self, reason):
        # Leave no cached report/evidence even on a malformed/stale ACK.
        self.state, self.reason = 'FAULT', reason
        self.deadline = self.stable_at = None
        return self._invalidate()

    def _clock(self, now):
        if (type(now) not in (int, float) or not math.isfinite(now) or now < 0 or
                (self.last_time is not None and now < self.last_time)):
            self._fail('INVALID_OR_BACKWARDS_MOTION_CLOCK')
            raise ValueError('Invalid/backwards motion clock')
        self.last_time = now
        if self.state == 'MOVING' and now >= self.deadline:
            self._fail('MOVEMENT_TIMEOUT')
        elif self.state == 'SETTLING' and now >= self.stable_at:
            self.state, self.reason = 'STABLE', None
            self.stable_at = None

    def begin_move(self, now):
        self._clock(now)
        if self.state != 'STABLE':
            self._fail('MOVE_WHILE_NOT_STABLE')
            raise ValueError('Move requires stable view; no queued motions')
        report = self._invalidate()
        self.state, self.reason = 'MOVING', 'CAMERA_MOVING'
        self.deadline = now + self.settings.movement_timeout_seconds
        return report

    def acknowledge_motion_complete(self, epoch, now):
        """External adapter ACK, not generated by a timer or Servo.write().

        A normal hobby-servo command/ACK without feedback is not position proof;
        evaluate suitable commissioning/feedback before deploying this gate.
        Exact-deadline ACK fails. A stale/duplicate ACK cannot unlock the view.
        """
        self._clock(now)
        if (self.state != 'MOVING' or type(epoch) is not int or
                epoch != self.tracker.camera_view_epoch):
            self._fail('INVALID_OR_STALE_MOTION_ACK')
            raise ValueError('ACK must match the outstanding view epoch')
        self.state, self.reason = 'SETTLING', 'CAMERA_SETTLING'
        self.deadline = None
        self.stable_at = now + self.settings.settle_seconds

    def recover_after_pose_verified(self, now):
        """Explicit operator/validated-adapter recovery; never auto-retry motors."""
        self._clock(now)
        if self.state != 'FAULT':
            self._fail('RECOVERY_WHILE_NOT_FAULTED')
            raise ValueError('Recovery requires FAULT')
        report = self._invalidate()
        self.state, self.reason = 'SETTLING', 'RECOVERED_POSE_SETTLING'
        self.stable_at = now + self.settings.settle_seconds
        return report

    def snapshot(self, now):
        """Save this at exposure, not when buffered inference finishes.

        If epoch/stability changes DURING exposure, drop that frame too. The
        future capture adapter owns this check and queue draining. Snapshot has
        no servo angles, no physical-ready claim and no hardware effects.
        """
        self._clock(now)
        return CameraView(self.tracker.camera_view_epoch, self.state != 'STABLE',
                          self.state, self.reason)
